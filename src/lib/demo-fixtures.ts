/**
 * Canned AI output for the public demo account.
 *
 * The demo has full CRUD but never calls Anthropic, so every generation type
 * needs a fixture. Fixtures are interpolated with the real job's company and
 * role so the output reads as genuinely tailored rather than obviously static,
 * and the structured-document types are persisted as real Document records so
 * DOCX export works from the demo exactly as it does for a real user.
 */

const DEMO_MODEL = "claude-sonnet-4-5 (demo fixture)";

/**
 * Appended to free-text demo output so the label sits with the content itself,
 * not only in the page banner. A visitor who copies the text, or who lands
 * straight on a generated document, still sees what it is.
 */
export const DEMO_OUTPUT_NOTE =
  "*Demo output: written in advance, not generated by Claude. Sign up to generate this from your own resume and job description.*";


export type DemoJob = {
  _id: string;
  company: string;
  role: string;
  location?: string | null;
};

const { name: PERSONA_NAME, firstName: PERSONA_FIRST_NAME } = DEMO_PERSONA;
const YEARS = DEMO_PERSONA.yearsExperience;
const CURRENT_EMPLOYER = DEMO_PERSONA.experience[0].company;

