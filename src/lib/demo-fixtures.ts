export function demoOutreach(type: string, job: DemoJob): string {
  const build = OUTREACH_FIXTURES[type];
  if (build) return `${build(job)}\n\n${DEMO_OUTPUT_NOTE}`;
  return `No demo fixture exists for the "${type}" generator yet.\n\n${DEMO_OUTPUT_NOTE}`;
}

export function demoAnalysis(job: DemoJob): JDAnalysis {
  return demoJDAnalysis(job);
}

export function demoPrep(job: DemoJob): InterviewPrep {
  return demoInterviewPrep(job);
}

/**
 * Builds and persists a demo resume or cover letter. Writing a real Document
 * record keeps the demo honest end to end: the export button downloads a DOCX
 * built by the same pipeline a paying user would hit.
 */
export async function demoStructuredDocument(
  userId: string,
  job: DemoJob,
  type: "resume" | "cover_letter"
): Promise<{ documentId: string; content: string; structuredContent: GeneratedResume | GeneratedCoverLetter }> {
  const structuredContent =
    type === "resume" ? demoResume(job) : demoCoverLetter(job);
  // Note goes on the rendered markdown only. structuredContent stays clean so
  // the exported DOCX and LaTeX carry no demo boilerplate.
  const content = `${generatedDocumentToMarkdown(structuredContent)}\n\n${DEMO_OUTPUT_NOTE}`;

  const saved = await documents.upsert(userId, {
    jobId: job._id,
    type,
    content,
    structuredContent: structuredContent as unknown as Record<string, unknown>,
    aiModel: DEMO_MODEL,
    inputTokens: 0,
    outputTokens: 0,
  });

  return { documentId: saved._id, content, structuredContent };
}

